def write_csv(path: Path, rows: list[dict[str, Any]], columns: list[str], repo_root: Path) -> None:
    ensure_can_write(path, repo_root)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, extrasaction="ignore", lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({column: as_text(row.get(column)) for column in columns})
    os.replace(tmp, path)


def write_text(path: Path, text: str, repo_root: Path) -> None:
    ensure_can_write(path, repo_root)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def write_json(path: Path, payload: dict[str, Any], repo_root: Path) -> None:
    ensure_can_write(path, repo_root)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def ensure_can_write(path: Path, repo_root: Path) -> None:
    rel = relpath(path, repo_root)
    if rel not in ALLOWED_GENERATED_RELATIVE_PATHS:
        raise RuntimeError(f"Refusing to write unapproved path: {rel}")
    if not path.exists():
        return
    metadata = repo_root / "reports/experiment_registry/registry_build_metadata.json"
    if path.suffix in {".md"}:
        head = read_limited_text(path, max_bytes=4096)
        if GENERATOR_MARKER in head:
            return
    if metadata.exists():
        data, _ = read_json(metadata)
        generated = set(data.get("generated_files", []))
        if rel in generated and data.get("script") == "scripts/build_experiment_registry.py":
            return
    raise RuntimeError(f"Refusing to overwrite a file not known to be registry-generated: {rel}")


def markdown_table(rows: list[dict[str, Any]], columns: list[str], limit: int = 20) -> str:
    shown = rows[:limit]
    if not shown:
        return "_None found._\n"
    out = ["|" + "|".join(columns) + "|", "|" + "|".join(["---"] * len(columns)) + "|"]
    for row in shown:
        out.append("|" + "|".join(as_text(row.get(column, "")).replace("|", "/") for column in columns) + "|")
    if len(rows) > limit:
        out.append(f"\n_Showing {limit} of {len(rows)} rows._")
    return "\n".join(out) + "\n"


