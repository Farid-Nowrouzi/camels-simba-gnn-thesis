def as_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        if math.isnan(value) or math.isinf(value):
            return ""
        return f"{value:.12g}"
    if isinstance(value, (list, tuple, set)):
        return ";".join(str(v) for v in value)
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def read_json(path: Path) -> tuple[dict[str, Any], str]:
    try:
        with path.open("r", encoding="utf-8") as handle:
            data = json.load(handle)
        if isinstance(data, dict):
            return data, ""
        return {}, "JSON root is not an object"
    except Exception as exc:  # noqa: BLE001 - registry must continue.
        return {}, str(exc)


def read_limited_text(path: Path, max_bytes: int = 1_000_000) -> str:
    try:
        if path.stat().st_size > max_bytes:
            return ""
        return path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ""


def stable_hash(payload: Any, length: int = 16) -> str:
    raw = json.dumps(payload, sort_keys=True, default=str, separators=(",", ":"))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:length]


def run_git(repo_root: Path, args: list[str]) -> str:
    try:
        proc = subprocess.run(
            ["git", *args],
            cwd=repo_root,
            check=False,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
        )
        return proc.stdout.strip()
    except Exception:
        return ""


def relpath(path: Path, repo_root: Path) -> str:
    try:
        return str(path.relative_to(repo_root))
    except ValueError:
        return str(path)


def find_experiment_dirs(experiments_root: Path) -> list[Path]:
    if not experiments_root.exists():
        return []
    markers = {
        "config.json",
        "metrics.json",
        "train_log.csv",
        "summary_features.csv",
    }
    dirs: list[Path] = []
    for path in sorted(experiments_root.rglob("*")):
        if not path.is_dir():
            continue
        has_marker = any((path / marker).exists() for marker in markers)
        has_predictions = (path / "predictions").is_dir()
        has_checkpoint_dir = (path / "checkpoints").is_dir()
        has_diagnostics = (path / "diagnostics").is_dir()
        if has_marker or has_predictions or has_checkpoint_dir or has_diagnostics:
            dirs.append(path)
    return dirs


def infer_int(patterns: Iterable[str], text: str) -> tuple[int | None, bool]:
    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE)
        if match:
            return int(match.group(1)), True
    return None, False


def infer_normalization(text: str) -> tuple[str, bool]:
    lowered = text.lower()
    for value in ["minmax", "zscore", "none"]:
        if re.search(rf"(^|[_/-]){value}($|[_/-])", lowered) or f"logmass_{value}" in lowered:
            return value, True
    return "", False


def find_dataset_metadata(repo_root: Path, dataset_path: str) -> tuple[dict[str, Any], str, str]:
    if not dataset_path:
        return {}, "", ""
    dataset = repo_root / dataset_path
    candidates = [
        dataset.with_suffix(".metadata.json"),
        dataset.with_name(dataset.stem + ".metadata.json"),
        dataset.with_name(dataset.stem + "_metadata.json"),
        dataset.with_name(dataset.stem + ".json"),
    ]
    for candidate in candidates:
        if candidate.exists() and candidate.suffix == ".json":
            data, error = read_json(candidate)
            if data:
                return data, relpath(candidate, repo_root), error
    return {}, "", ""


def split_signature(config: dict[str, Any]) -> str:
    train_ids = config.get("train_ids")
    val_ids = config.get("val_ids")
    test_ids = config.get("test_ids")
    if not all(isinstance(x, list) for x in [train_ids, val_ids, test_ids]):
        return ""
    payload = {
        "train": sorted(str(x) for x in train_ids),
        "val": sorted(str(x) for x in val_ids),
        "test": sorted(str(x) for x in test_ids),
    }
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def select_metric(metrics: dict[str, Any], key: str) -> Any:
    test = metrics.get("test")
    if isinstance(test, dict):
        aliases = {
            "mae": ["mae", "MAE", "test_mae"],
            "rmse": ["rmse", "RMSE", "test_rmse"],
            "mse": ["mse", "MSE", "test_mse"],
            "r2": ["r2", "R2", "r2_score", "test_r2"],
            "pearson": ["pearson", "correlation", "test_pearson"],
        }
        for alias in aliases.get(key, [key]):
            if alias in test:
                return test[alias]
    for alias in [f"test_{key}", key]:
        if alias in metrics:
            return metrics[alias]
    return None


def extract_saved_metrics(metrics: dict[str, Any], notes: list[str]) -> dict[str, Any]:
    result = {
        "model_from_metrics": "",
        "test_mae_saved": select_metric(metrics, "mae"),
        "test_rmse_saved": select_metric(metrics, "rmse"),
        "test_mse_saved": select_metric(metrics, "mse"),
        "test_r2_saved": select_metric(metrics, "r2"),
        "test_pearson_saved": select_metric(metrics, "pearson"),
        "best_epoch": metrics.get("best_epoch"),
        "best_val_loss": metrics.get("best_val_mse") or metrics.get("best_val_loss"),
    }
    nested = metrics.get("results")
    if isinstance(nested, dict):
        best_name = ""
        best = None
        summaries = []
        for model_name, model_metrics in sorted(nested.items()):
            if not isinstance(model_metrics, dict):
                continue
            test = model_metrics.get("test")
            if not isinstance(test, dict):
                continue
            mae = test.get("mae")
            rmse = test.get("rmse")
            summaries.append(f"{model_name}:mae={mae},rmse={rmse}")
            if mae is not None and (best is None or float(mae) < float(best.get("mae"))):
                best_name = model_name
                best = test
        if best is not None:
            result["model_from_metrics"] = best_name
            result["test_mae_saved"] = best.get("mae")
            result["test_rmse_saved"] = best.get("rmse")
            result["test_mse_saved"] = best.get("mse")
            result["test_r2_saved"] = best.get("r2")
            notes.append("summary baseline row uses best nested test MAE model: " + best_name)
        if summaries:
            notes.append("nested baseline metrics: " + " | ".join(summaries))
    return result


def choose_column(fields: list[str], kind: str) -> tuple[str, str]:
    lowered = {field.lower(): field for field in fields}
    if kind == "target":
        priority = [
            "true_omega_m",
            "target_omega_m",
            "omega_m_true",
            "y_true",
            "target",
            "true",
            "actual",
            "omega_m",
        ]
        substrings = ["true", "target", "actual"]
    else:
        priority = [
            "pred_omega_m",
            "predicted_omega_m",
            "omega_m_pred",
            "y_pred",
            "prediction",
            "predicted",
            "pred",
        ]
        substrings = ["pred"]
    for name in priority:
        if name in lowered:
            return lowered[name], ""
    candidates = [
        field
        for field in fields
        if any(part in field.lower() for part in substrings)
    ]
    if len(candidates) == 1:
        return candidates[0], ""
    if len(candidates) > 1:
        return "", f"ambiguous {kind} columns: {candidates}"
    return "", f"missing {kind} column"


def recompute_prediction_metrics(path: Path) -> dict[str, Any]:
    empty = {
        "test_mae_recomputed": None,
        "test_rmse_recomputed": None,
        "test_mse_recomputed": None,
        "test_r2_recomputed": None,
        "pearson_recomputed": None,
        "target_mean": None,
        "target_std": None,
        "target_min": None,
        "target_max": None,
        "prediction_mean": None,
        "prediction_std": None,
        "prediction_min": None,
        "prediction_max": None,
        "prediction_std_ratio": None,
        "prediction_bias": None,
        "repeated_prediction_count": None,
        "repeated_prediction_fraction": None,
        "unique_prediction_count": None,
        "test_prediction_count": None,
        "predictions_parse_error": "",
    }
    if not path.exists():
        return empty
    try:
        with path.open("r", encoding="utf-8", newline="") as handle:
            reader = csv.DictReader(handle)
            fields = reader.fieldnames or []
            target_col, target_error = choose_column(fields, "target")
            pred_col, pred_error = choose_column(fields, "prediction")
            errors = [err for err in [target_error, pred_error] if err]
            if errors:
                empty["predictions_parse_error"] = "; ".join(errors)
                return empty
            targets: list[float] = []
            predictions: list[float] = []
            for index, row in enumerate(reader, start=2):
                try:
                    target = float(row[target_col])
                    prediction = float(row[pred_col])
                except Exception as exc:  # noqa: BLE001
                    empty["predictions_parse_error"] = f"row {index}: {exc}"
                    return empty
                if math.isnan(target) or math.isnan(prediction):
                    empty["predictions_parse_error"] = f"row {index}: NaN value"
                    return empty
                targets.append(target)
                predictions.append(prediction)
    except Exception as exc:  # noqa: BLE001
        empty["predictions_parse_error"] = str(exc)
        return empty
    n = len(targets)
    if n == 0:
        empty["predictions_parse_error"] = "empty prediction file"
        return empty
    errors = [p - t for t, p in zip(targets, predictions)]
    abs_errors = [abs(err) for err in errors]
    squared_errors = [err * err for err in errors]
    mae = sum(abs_errors) / n
    mse = sum(squared_errors) / n
    rmse = math.sqrt(mse)
    target_mean = sum(targets) / n
    prediction_mean = sum(predictions) / n
    target_var = sum((x - target_mean) ** 2 for x in targets) / n
    prediction_var = sum((x - prediction_mean) ** 2 for x in predictions) / n
    target_std = math.sqrt(target_var)
    prediction_std = math.sqrt(prediction_var)
    sst = sum((x - target_mean) ** 2 for x in targets)
    r2 = None if sst == 0 else 1.0 - (sum(squared_errors) / sst)
    pearson = None
    if n >= 2 and target_std > 0 and prediction_std > 0:
        cov = sum((t - target_mean) * (p - prediction_mean) for t, p in zip(targets, predictions)) / n
        pearson = cov / (target_std * prediction_std)
    rounded = [round(value, 6) for value in predictions]
    counts = Counter(rounded)
    repeated = counts.most_common(1)[0][1]
    empty.update(
        {
            "test_mae_recomputed": mae,
            "test_rmse_recomputed": rmse,
            "test_mse_recomputed": mse,
            "test_r2_recomputed": r2,
            "pearson_recomputed": pearson,
            "target_mean": target_mean,
            "target_std": target_std,
            "target_min": min(targets),
            "target_max": max(targets),
            "prediction_mean": prediction_mean,
            "prediction_std": prediction_std,
            "prediction_min": min(predictions),
            "prediction_max": max(predictions),
            "prediction_std_ratio": None if target_std == 0 else prediction_std / target_std,
            "prediction_bias": prediction_mean - target_mean,
            "repeated_prediction_count": repeated,
            "repeated_prediction_fraction": repeated / n,
            "unique_prediction_count": len(counts),
            "test_prediction_count": n,
        }
    )
    return empty


def classify_family(name: str, path: str, config: dict[str, Any], metrics: dict[str, Any]) -> str:
    lowered = f"{path}/{name}".lower()
    model = str(config.get("model", ""))
    if "archive_mixed_architecture" in lowered:
        return "archived_experiment"
    if "debug_overfit" in lowered:
        return "debug_overfit"
    if "debug" in lowered:
        if "summary" in lowered:
            return "feature_validation"
        if "mean_baseline" in lowered:
            return "target_validation"
        return "debug_overfit"
    if "summary_mlp" in lowered:
        return "summary_mlp_baseline"
    if "summary_features" in lowered:
        return "summary_baseline"
    if "hybrid_summary" in lowered:
        return "hybrid_gnn_summary"
    if "graphsage" in lowered or config.get("conv_type") == "graphsage":
        return "graph_convolution_ablation"
    if "linear_head_temporal_last" in lowered:
        return "temporal_pooling_ablation"
    if "linear_head_meanmax" in lowered or "meanmax" in lowered:
        return "graph_pooling_ablation"
    if "750u_top1000" in lowered and ("linear_head" in lowered or config.get("head_type") in {"linear", "mlp"}):
        return "head_ablation"
    if re.search(r"_k(4|6|8|12)_", lowered):
        return "knn_ablation"
    if "top200" in lowered:
        return "top_n_scaling"
    if "top500" in lowered and any(token in lowered for token in ["_none", "_minmax", "_zscore"]):
        return "normalization_ablation"
    if "mean_baseline" in lowered:
        return "target_validation"
    if model == "StaticGCNRegressor":
        return "static_gcn"
    if model == "EvolveGCNHRegressor":
        return "universe_scaling"
    return "other"


def classify_type(family: str, name: str) -> tuple[str, str, str, str, str]:
    if family in {"head_ablation", "graph_pooling_ablation", "temporal_pooling_ablation", "normalization_ablation", "knn_ablation", "graph_convolution_ablation"}:
        variables = {
            "head_ablation": "head_type",
            "graph_pooling_ablation": "graph_pooling",
            "temporal_pooling_ablation": "temporal_pooling",
            "normalization_ablation": "normalization",
            "knn_ablation": "k",
            "graph_convolution_ablation": "conv_type",
        }
        return "controlled_ablation", "controlled", "controlled thesis evidence", variables[family], variables[family]
    if family in {"universe_scaling", "top_n_scaling"}:
        variable = "universes" if family == "universe_scaling" else "top_n"
        return "partly_controlled_comparison", "partly_controlled", "development story evidence", variable, variable
    if family in {"summary_baseline", "summary_mlp_baseline", "target_validation"}:
        return "baseline", "not_applicable", "baseline or sanity check", "model_family", "model_family"
    if family in {"prediction_collapse_diagnostic", "representation_probe", "linear_probe", "feature_validation", "split_validation", "debug_overfit"}:
        kind = "debug" if family == "debug_overfit" else "diagnostic"
        return kind, "not_applicable", "diagnostic evidence", "", ""
    if family == "archived_experiment":
        return "exploratory_experiment", "unknown", "archived historical evidence", "", ""
    if "debug" in name.lower():
        return "debug", "not_applicable", "debug evidence", "", ""
    return "exploratory_experiment", "unknown", "supporting evidence", "", ""


