def apply_grouping(rows: list[dict[str, Any]]) -> None:
    duplicates = defaultdict(list)
    for row in rows:
        duplicates[fingerprint(row)].append(row)
    dup_index = 1
    for _, group in sorted(duplicates.items(), key=lambda item: item[0]):
        if len(group) <= 1:
            continue
        group_id = f"duplicate_group_{dup_index:03d}"
        group.sort(key=lambda row: row["experiment_path"])
        for index, row in enumerate(group):
            row["duplicate_group"] = group_id
            row["likely_duplicate"] = True
            row["original_or_reproduction"] = "original" if index == 0 else "reproduction"
            if index > 0:
                row["status"] = "duplicate_reproduction"
                row["experiment_type"] = "reproduction"
                row["scientific_role"] = "duplicate/reproduction check"
                row["notes"] = (row.get("notes") + " | " if row.get("notes") else "") + f"duplicate of {group[0]['experiment_path']}"
        dup_index += 1
    for row in rows:
        row["seed_family"] = seed_family_key(row)
        row["directly_comparable_group"] = comparable_group(row)
    families = defaultdict(list)
    for row in rows:
        if row["status"] == "duplicate_reproduction":
            continue
        families[row["seed_family"]].append(row)
    for group in families.values():
        seeds = sorted({int(row["seed"]) for row in group if str(row.get("seed", "")).isdigit()})
        expected = MAIN_SEED_SET if any(seed in [777, 999] for seed in seeds) or len(seeds) >= 5 else EARLY_SEED_SET
        missing = [seed for seed in expected if seed not in seeds]
        for row in group:
            row["expected_seed_set"] = ",".join(str(seed) for seed in expected)
            row["family_seed_count"] = len(seeds)
            row["family_missing_seeds"] = ",".join(str(seed) for seed in missing)


def add_artifact_matches(repo_root: Path, rows: list[dict[str, Any]], artifact_rows: list[dict[str, Any]]) -> None:
    name_to_row = {row["experiment_name"]: row for row in rows}
    notebook_matches = defaultdict(list)
    output_matches = defaultdict(list)
    eval_matches = defaultdict(list)
    for artifact in artifact_rows:
        path = artifact["artifact_path"]
        refs = [ref for ref in artifact.get("referenced_experiments", "").split(";") if ref]
        for ref in refs:
            if ref in name_to_row:
                if artifact["artifact_type"] == "notebook":
                    notebook_matches[ref].append(path)
                elif artifact["artifact_type"] in {"output_summary", "output_artifact"}:
                    output_matches[ref].append(path)
                elif artifact["artifact_type"] == "evaluation_script":
                    eval_matches[ref].append(path)
    for row in rows:
        row["notebook_matches"] = ";".join(sorted(notebook_matches[row["experiment_name"]]))
        row["output_summary_matches"] = ";".join(sorted(output_matches[row["experiment_name"]]))
        row["evaluation_script_matches"] = ";".join(sorted(eval_matches[row["experiment_name"]]))


def discover_artifacts(repo_root: Path, experiment_names: list[str]) -> list[dict[str, Any]]:
    artifact_rows: list[dict[str, Any]] = []
    datasets_regex = re.compile(r"data/processed/[A-Za-z0-9_./\\-]+\\.pt")
    roots = [
        ("notebooks", "notebook"),
        ("outputs", "output_artifact"),
        ("reports", "report"),
        ("src/evaluation", "evaluation_script"),
        ("presentation_assets", "presentation_asset"),
    ]
    stale_paths = {
        "outputs/evolvegcn_500u_vs_750u_results/seed_level_results_clean.csv",
        "outputs/evolvegcn_500top500_vs_750top1000_5seed_table.csv",
    }
    for rel_root, artifact_type in roots:
        root = repo_root / rel_root
        if not root.exists():
            continue
        for path in sorted(p for p in root.rglob("*") if p.is_file()):
            rel = relpath(path, repo_root)
            suffix = path.suffix.lower()
            if rel.startswith("outputs/") and suffix in {".png", ".html", ".csv", ".json", ".md", ".txt"}:
                artifact_type_current = "output_summary" if suffix in {".csv", ".json", ".md"} else "output_artifact"
            else:
                artifact_type_current = artifact_type
            text = ""
            if suffix in {".ipynb", ".csv", ".json", ".md", ".py", ".txt", ".sh"}:
                text = read_limited_text(path)
            refs = sorted(name for name in experiment_names if name in text or name in path.name)
            datasets = sorted(set(datasets_regex.findall(text)))
            family = notebook_family(path) if artifact_type_current == "notebook" else output_family(path)
            if artifact_type_current == "evaluation_script":
                family = output_family(path)
            appears_stale = rel in stale_paths
            artifact_rows.append(
                {
                    "artifact_path": rel,
                    "artifact_type": artifact_type_current,
                    "likely_experiment_family": family,
                    "referenced_experiments": ";".join(refs[:50]),
                    "referenced_datasets": ";".join(datasets[:20]),
                    "appears_current": "" if appears_stale else "unknown",
                    "appears_stale": appears_stale,
                    "mapping_confidence": "medium" if family != "other" else "low",
                    "notes": "known stale candidate" if appears_stale else "",
                }
            )
    return artifact_rows


def raw_metric_lookup(rows: list[dict[str, Any]]) -> dict[str, dict[str, float]]:
    lookup: dict[str, dict[str, float]] = {}
    for row in rows:
        metrics: dict[str, float] = {}
        for metric, saved, recomputed in [
            ("mae", "test_mae_saved", "test_mae_recomputed"),
            ("rmse", "test_rmse_saved", "test_rmse_recomputed"),
            ("r2", "test_r2_saved", "test_r2_recomputed"),
        ]:
            value = row.get(recomputed)
            if value in ("", None):
                value = row.get(saved)
            try:
                if value not in ("", None):
                    metrics[metric] = float(value)
            except Exception:
                pass
        lookup[row["experiment_name"]] = metrics
    return lookup


def audit_stale_outputs(repo_root: Path, rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    lookup = raw_metric_lookup(rows)
    mismatches: list[dict[str, Any]] = []
    output_root = repo_root / "outputs"
    if not output_root.exists():
        return mismatches
    metric_columns = {
        "mae": ["mae"],
        "rmse": ["rmse"],
        "r2": ["r2"],
    }
    for csv_path in sorted(output_root.rglob("*.csv")):
        try:
            with csv_path.open("r", encoding="utf-8", newline="") as handle:
                reader = csv.DictReader(handle)
                fields = reader.fieldnames or []
                name_col = next((field for field in fields if field.lower() in {"experiment", "experiment_name", "name"}), "")
                if not name_col:
                    continue
                for row in reader:
                    exp_name = row.get(name_col, "")
                    if exp_name not in lookup:
                        continue
                    for metric_name, tokens in metric_columns.items():
                        current = lookup[exp_name].get(metric_name)
                        if current is None:
                            continue
                        candidate_cols = []
                        for field in fields:
                            lower = field.lower()
                            is_test_metric = (
                                lower in {metric_name, f"test_{metric_name}", f"test {metric_name}"}
                                or lower.startswith(f"test_{metric_name}")
                                or lower.startswith(f"test {metric_name}")
                                or lower == f"test_{metric_name}_from_predictions"
                            )
                            if (
                                any(token in lower for token in tokens)
                                and is_test_metric
                                and "std" not in lower
                                and "mean" not in lower
                            ):
                                candidate_cols.append(field)
                        for column in candidate_cols:
                            raw = row.get(column)
                            if raw in ("", None):
                                continue
                            try:
                                old = float(raw)
                            except Exception:
                                continue
                            diff = abs(old - current)
                            if diff > STALE_TOLERANCE:
                                mismatches.append(
                                    {
                                        "file": relpath(csv_path, repo_root),
                                        "experiment": exp_name,
                                        "metric": column,
                                        "stale_value": old,
                                        "current_value": current,
                                        "absolute_difference": diff,
                                        "recommended_source": f"experiments/{exp_name}/metrics.json and predictions/test_predictions.csv",
                                    }
                                )
        except Exception:
            continue
    return mismatches


def aggregate_values(values: list[float]) -> tuple[str, str]:
    if not values:
        return "", ""
    mean = statistics.mean(values)
    std = statistics.stdev(values) if len(values) >= 2 else 0.0
    return f"{mean:.12g}", f"{std:.12g}"


