def build_metadata(repo_root: Path, rows: list[dict[str, Any]], errors: list[str], warnings_count: int) -> dict[str, Any]:
    status = run_git(repo_root, ["status", "--short"])
    return {
        "script": "scripts/build_experiment_registry.py",
        "script_version": SCRIPT_VERSION,
        "registry_generation_timestamp": datetime.now(timezone.utc).isoformat(),
        "repository_root": str(repo_root),
        "current_git_branch": run_git(repo_root, ["branch", "--show-current"]),
        "current_git_commit": run_git(repo_root, ["rev-parse", "HEAD"]),
        "current_git_dirty_state": "dirty" if status else "clean",
        "python_version": sys.version,
        "platform": platform.platform(),
        "number_of_folders_scanned": len(rows),
        "number_of_rows_generated": len(rows),
        "warnings_count": warnings_count,
        "errors_count": len(errors),
        "generated_files": ALLOWED_GENERATED_RELATIVE_PATHS,
    }


def write_outputs(
    repo_root: Path,
    report_dir: Path,
    rows: list[dict[str, Any]],
    family_rows: list[dict[str, Any]],
    artifact_rows: list[dict[str, Any]],
    issues: list[dict[str, Any]],
    stale: list[dict[str, Any]],
    errors: list[str],
) -> None:
    write_csv(report_dir / "master_experiment_registry.csv", rows, MASTER_COLUMNS, repo_root)
    write_csv(report_dir / "experiment_family_summary.csv", family_rows, FAMILY_COLUMNS, repo_root)
    write_csv(report_dir / "incomplete_or_duplicate_experiments.csv", issues, ISSUE_COLUMNS, repo_root)
    write_csv(report_dir / "analysis_artifact_index.csv", artifact_rows, ARTIFACT_COLUMNS, repo_root)
    write_text(report_dir / "master_experiment_registry.md", build_master_markdown(rows, family_rows, issues, stale), repo_root)
    write_text(report_dir / "registry_validation_report.md", build_validation_report(rows, issues, stale, errors, len(rows)), repo_root)
    write_text(report_dir / "professor_request_experiment_inventory.md", build_professor_report(rows, family_rows), repo_root)
    metadata = build_metadata(repo_root, rows, errors, warnings_count=len(issues) + len(stale))
    write_json(report_dir / "registry_build_metadata.json", metadata, repo_root)
    write_text(repo_root / "docs/experiment_naming_convention.md", build_naming_doc(), repo_root)


def print_summary(rows: list[dict[str, Any]], family_rows: list[dict[str, Any]], issues: list[dict[str, Any]], stale: list[dict[str, Any]], errors: list[str], validate_only: bool) -> None:
    print("Experiment registry scan complete")
    print(f"validate_only: {validate_only}")
    print(f"registry_rows: {len(rows)}")
    print("status_counts:")
    for key, value in Counter(row["status"] for row in rows).most_common():
        print(f"  {key}: {value}")
    print("experiment_family_counts:")
    for key, value in Counter(row["experiment_family"] for row in rows).most_common():
        print(f"  {key}: {value}")
    print(f"family_summary_rows: {len(family_rows)}")
    print(f"issue_rows: {len(issues)}")
    print(f"stale_mismatches: {len(stale)}")
    print(f"errors: {len(errors)}")
    duplicates = sorted({row["duplicate_group"] for row in rows if row["duplicate_group"]})
    print(f"duplicate_groups: {len(duplicates)}")
    for group in duplicates:
        names = [row["experiment_name"] for row in rows if row["duplicate_group"] == group]
        print(f"  {group}: {', '.join(names)}")


def build_registry(repo_root: Path, experiments_root: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], list[str]]:
    rows, errors = build_experiment_rows(repo_root, experiments_root)
    apply_grouping(rows)
    merge_training_scaling_matrix(repo_root, rows, errors)
    artifact_rows = discover_artifacts(repo_root, [row["experiment_name"] for row in rows])
    stale = audit_stale_outputs(repo_root, rows)
    for artifact in artifact_rows:
        if any(item["file"] == artifact["artifact_path"] for item in stale):
            artifact["appears_stale"] = True
            artifact["appears_current"] = ""
            artifact["notes"] = (artifact["notes"] + "; " if artifact["notes"] else "") + "metric values disagree with current raw experiment files"
    add_artifact_matches(repo_root, rows, artifact_rows)
    family_rows = build_family_summaries(rows)
    issues = build_issue_rows(rows)
    return rows, family_rows, artifact_rows, issues, stale, errors


def merge_training_scaling_matrix(repo_root: Path, rows: list[dict[str, Any]], errors: list[str]) -> None:
    """Merge the tracked lifecycle source into the canonical registry output.

    Existing experiment rows are augmented by experiment name; planned rows are
    appended. Historical non-matrix rows and their original schema semantics are
    otherwise untouched.
    """
    source = repo_root / "configs/experiment_registry/u1000_top1000_training_scaling_matrix.json"
    if not source.is_file():
        return
    try:
        payload = json.loads(source.read_text(encoding="utf-8"))
        entries = payload["entries"]
    except Exception as exc:  # noqa: BLE001
        errors.append(f"{relpath(source, repo_root)}: {exc}")
        return
    by_name = {str(row.get("experiment_name")): row for row in rows}
    matrix_fields = [field for field in MASTER_COLUMNS if field in {
        "matrix_included", "training_universe_count", "master_dataset_path", "dataset_sha256",
        "metadata_sha256", "completion_marker_sha256", "target_table_sha256", "split_manifest_path",
        "split_manifest_sha256", "configuration_path", "experiment_directory", "repository_commit",
        "graph_storage_mode", "snapshot_input_protocol", "planned_timestamp", "launch_timestamp",
        "completion_timestamp", "validation_timestamp", "failure_reason", "invalid_reason",
        "checkpoint_path", "metrics_path", "predictions_path", "epochs_executed", "runtime_seconds",
        "peak_gpu_memory_mib", "validation_result", "test_mae", "test_rmse", "test_mse", "test_r2",
        "prediction_standard_deviation", "target_standard_deviation", "residual_mean",
        "residual_standard_deviation", "low_target_bias", "high_target_bias", "collapse_flag",
    }]
    aliases = {
        "prediction_mean": "prediction_mean_matrix",
        "prediction_sd_ratio": "prediction_sd_ratio_matrix",
        "repeated_prediction_count": "repeated_prediction_count_matrix",
        "repeated_prediction_fraction": "repeated_prediction_fraction_matrix",
    }
    for entry in entries:
        name = str(entry.get("experiment_name", ""))
        row = by_name.get(name)
        if row is None:
            row = {column: "" for column in MASTER_COLUMNS}
            row.update({
                "experiment_name": name,
                "experiment_path": entry.get("experiment_directory", ""),
                "experiment_type": "planned_training",
                "experiment_family": "u1000_top1000_training_scaling",
                "scientific_role": "fixed-holdout training-universe learning curve",
                "model": entry.get("model", ""),
                "seed": entry.get("seed", ""),
                "train_count": entry.get("training_universe_count", ""),
                "val_count": entry.get("validation_count", ""),
                "test_count": entry.get("test_count", ""),
                "dataset_path": entry.get("master_dataset_path", ""),
                "top_n": entry.get("top_n", ""),
                "normalization": entry.get("normalization", ""),
                "k": entry.get("k", ""),
            })
            rows.append(row)
            by_name[name] = row
        row["canonical_experiment_id"] = entry.get("canonical_experiment_id", "")
        row["status"] = entry.get("status", row.get("status", ""))
        for field in matrix_fields:
            row[field] = entry.get(field, "")
        for source_field, output_field in aliases.items():
            row[output_field] = entry.get(source_field, "")
        row["notes"] = (str(row.get("notes") or "") + " | " if row.get("notes") else "") + (
            "U1000 training-scaling matrix lifecycle entry"
            if entry.get("matrix_included") else "invalid attempt preserved and excluded from scientific matrix"
        )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build a read-only CAMELS thesis experiment registry.")
    parser.add_argument("--repo-root", type=Path, required=True, help="Repository root path.")
    parser.add_argument("--experiments-root", type=Path, default=Path("experiments"), help="Experiment root relative to repo root or absolute.")
    parser.add_argument("--report-dir", type=Path, default=Path("reports/experiment_registry"), help="Report directory relative to repo root or absolute.")
    parser.add_argument("--validate-only", action="store_true", help="Scan and print findings without writing generated reports.")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    repo_root = args.repo_root.resolve()
    experiments_root = args.experiments_root if args.experiments_root.is_absolute() else repo_root / args.experiments_root
    report_dir = args.report_dir if args.report_dir.is_absolute() else repo_root / args.report_dir
    rows, family_rows, artifact_rows, issues, stale, errors = build_registry(repo_root, experiments_root)
    print_summary(rows, family_rows, issues, stale, errors, args.validate_only)
    if not args.validate_only:
        write_outputs(repo_root, report_dir, rows, family_rows, artifact_rows, issues, stale, errors)
        print(f"reports_written: {report_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
